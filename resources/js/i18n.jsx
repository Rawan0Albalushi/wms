const LocaleContext = createContext(null);

export function LocaleProvider({ children }) {
    const [locale, setLocale] = useState(() => localStorage.getItem('wms-locale') || 'ar');

    useEffect(() => {
        document.documentElement.lang = locale;
        document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
        localStorage.setItem('wms-locale', locale);
    }, [locale]);

    const t = useCallback((key) => dict[locale]?.[key] ?? dict.ar[key] ?? key, [locale]);
    const value = useMemo(() => ({
        locale,
        setLocale: (next) => setLocale(next === 'ar' ? 'ar' : 'en'),
        toggle: () => setLocale((current) => (current === 'ar' ? 'en' : 'ar')),
        t,
    }), [locale, t]);

    return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
    return useContext(LocaleContext);
}
